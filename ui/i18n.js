const DICTS = { en: EN, fa: FA };
let locale = "en";
const listeners = new Set();

export const getLocale = () => locale;
export const isRtl = () => locale === "fa";

export function t(key, vars) {
  const dict = DICTS[locale] || EN;
  let text = dict[key] ?? EN[key] ?? key;
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (m, k) => {
      const value = vars[k];
      if (value === undefined) return m;
      return typeof value === "number" ? num(value) : String(value);
    });
  }
  return text;
}

/** Persian digits for numbers rendered by the UI (never for user content). */
export function num(value) {
  if (value === null || value === undefined) return "";
  if (locale !== "fa") return String(value);
  return toFa(value);
}

/** "0:42" → "۰:۴۲" in fa, unchanged in en. */
export const localizeDigits = (text) => (locale === "fa" ? toFa(text) : String(text));

export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

export function setLocale(next, { persist = true, silent = false } = {}) {
  locale = next === "fa" ? "fa" : "en";
  const html = document.documentElement;
  html.lang = locale;
  html.dir = locale === "fa" ? "rtl" : "ltr";
  html.dataset.locale = locale;
  applyStatic();
  if (persist) {
    try {
      localStorage.setItem("bloom.locale", locale);
    } catch (err) {
      /* storage may be full */
    }
  }
  listeners.forEach((fn) => fn(locale));
  if (!silent) document.dispatchEvent(new CustomEvent("bloom:locale", { detail: { locale } }));
  return locale;
}

export const onLocaleChange = (fn) => listeners.add(fn);
export const toggleLocale = () => setLocale(locale === "fa" ? "en" : "fa");
export const localeFromStorage = () => {
  try {
    return localStorage.getItem("bloom.locale") === "fa" ? "fa" : "en";
  } catch (err) {
    return "en";
  }
};
